"""Results survive a JSON round trip (NaN <-> null) and the README block is regenerated cleanly."""

from __future__ import annotations

from pathlib import Path

import pytest

from entity_cascade.eval.readme import END, START, render_block, update_readme
from entity_cascade.eval.report import EvalResults, render_markdown
from test_gate_unit import results


def nan_results() -> EvalResults:
    r = results()
    zones = r.zone_blocks[0].zones[0].model_copy(update={"top1_correct": float("nan")})
    block = r.zone_blocks[0].model_copy(update={"zones": [zones]})
    return r.model_copy(update={"zone_blocks": [block], "charts": ["a.png"]})


def test_json_round_trip_with_nan() -> None:
    r = nan_results()
    text = r.model_dump_json()
    assert "NaN" not in text  # strict JSON
    back = EvalResults.model_validate_json(text)
    assert back.zone_blocks[0].zones[0].top1_correct != back.zone_blocks[0].zones[0].top1_correct
    assert render_markdown(back) == render_markdown(r)


def test_markdown_shows_na_for_nan_and_marks_missing_llm() -> None:
    md = render_markdown(nan_results())
    assert "n/a" in md
    assert "![a.png](a.png)" in md


def test_update_readme_replaces_only_the_block(tmp_path: Path) -> None:
    p = tmp_path / "README.md"
    p.write_text(f"intro\n{START}\nold\n{END}\noutro\n", encoding="utf-8")
    update_readme(nan_results(), p)
    text = p.read_text(encoding="utf-8")
    assert text.startswith("intro\n") and text.endswith("\noutro\n")
    assert "STALE-BLOCK" not in text and "Generated by `make eval`" in text
    first = text
    update_readme(nan_results(), p)
    assert p.read_text(encoding="utf-8") == first  # idempotent


def test_update_readme_requires_markers(tmp_path: Path) -> None:
    p = tmp_path / "README.md"
    p.write_text("no markers here", encoding="utf-8")
    with pytest.raises(ValueError, match="markers"):
        update_readme(nan_results(), p)


def test_block_without_real_llm_says_so() -> None:
    block = render_block(nan_results())
    assert "no real LLM run is recorded" in block
