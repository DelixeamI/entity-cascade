"""Regenerate the numbers block of README.md from the eval results. No number is typed by hand."""

from __future__ import annotations

from pathlib import Path

from entity_cascade.eval.report import (
    EvalResults,
    SystemRow,
    _modes_section,
    _pct,
    _tradeoff_section,
    _transfer_section,
)

START = "<!-- results:start -->"
END = "<!-- results:end -->"


def _find(r: EvalResults, name: str) -> SystemRow | None:
    return next((s for s in r.systems if s.split == "test" and s.name == name), None)


def render_block(r: EvalResults) -> str:
    lines: list[str] = [
        "_Generated by `make eval` from `reports/results.json`. Do not edit between the markers._",
        "",
        f"Dataset `{r.dataset_name}`, seed {r.seed}. Thresholds are fitted on the val split, "
        "every number below is on the held-out test split unless it says otherwise.",
        "",
    ]
    base = _find(r, "accept every top-1 (no cascade)")
    casc = _find(r, "cascade, llm_arbiter rows go to a human")
    full = _find(r, "cascade + LLM arbiter")
    test_zones = next(z for z in r.zone_blocks if z.split == "test").zones
    auto = next(z for z in test_zones if z.zone == "auto_match")
    if base and casc:
        lines += [
            f"- Accepting every top-1 answer: precision {_pct(base.metrics.precision)} "
            f"with zero human work.",
            f"- Cascade without the LLM: {_pct(casc.metrics.automation_rate)} of rows answered "
            f"automatically, auto_match precision {_pct(auto.top1_correct)} "
            f"(target {_pct(r.target_precision)}), {_pct(casc.metrics.human_share)} of rows "
            f"left to a human; system precision {_pct(casc.metrics.precision)}, "
            f"recall {_pct(casc.metrics.recall)} when the human is right.",
        ]
    if full and r.llm is not None and not r.llm.stand_in:
        a = r.llm.metrics
        lines.append(
            f"- With the LLM arbiter (`{r.llm.model}`): {_pct(full.metrics.automation_rate)} "
            f"automated, {_pct(full.metrics.human_share)} to a human; it resolves "
            f"{_pct(a.resolved_share)} of the gray zone at {_pct(a.resolved_accuracy)} accuracy; "
            f"system precision {_pct(full.metrics.precision)}, recall "
            f"{_pct(full.metrics.recall)}; ${a.cost_usd_per_1000_rows:.4f} per 1000 rows."
        )
    else:
        lines.append(
            "- LLM arbiter: **no real LLM run is recorded in this checkout**, so no LLM "
            "numbers are shown. Run `make record` with a provider, then `make eval`."
        )
    lines.append("")
    for chart in r.charts:
        lines += [f"![{chart.removesuffix('.png')}](reports/{chart})", ""]
    lines += _modes_section(r, "####") + [""]
    lines += _tradeoff_section(r, "####") + [""]
    if r.secondary is not None:
        lines += _transfer_section(r.secondary, "####")[:8] + [""]
        lines.append("Full tables: [reports/results.md](reports/results.md).")
    return "\n".join(lines).rstrip() + "\n"


def update_readme(r: EvalResults, path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise ValueError(f"{path} lacks the {START} / {END} markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    path.write_text(f"{head}{START}\n{render_block(r)}{END}{tail}", encoding="utf-8")
